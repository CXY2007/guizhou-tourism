def current_lang():
    if has_request_context():
        lang = session.get("lang", "zh")
        return lang if lang in SUPPORTED else "zh"
    return "zh"


def t(text, **kwargs):
    value = EN.get(text, text) if current_lang() == "en" else text
    if kwargs:
        try:
            return value.format(**kwargs)
        except (KeyError, IndexError):
            return value
    return value


def lang_url(lang):
    args = request.args.to_dict(flat=True)
    args["lang"] = lang
    return request.path + "?" + urlencode(args)


def attr_field(attraction, field):
    if current_lang() == "en":
        translation = next((item for item in getattr(attraction, "translations", []) if item.lang == "en"), None)
        if translation is not None:
            value = getattr(translation, "poetic" if field == "poetic_description" else field, None)
            if value:
                return value
    return getattr(attraction, field, "") or ""


def category_label(category):
    return t(category)


def city_label(city):
    return t(city) if city else ""


def region_label(region):
    return t(region) if region else ""


def price_text(attraction):
    if current_lang() == "en":
        price = float(attraction.price or 0)
        return "Free" if price == 0 else f"¥{price:g}"
    return attraction.price_label


